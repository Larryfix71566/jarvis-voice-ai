"""Propose a model pin change as a GitHub PR, or as a patch file (WS-41).

Hard rules: never edit the local checkout, never merge, never push to the
base branch, never put an alias in a proposal, never leak the token.
"""
from __future__ import annotations

import base64
import difflib
import os
import re
import tempfile
from pathlib import Path
from typing import Any

from jarvis.model_sync import ids

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_REPO = "Larryfix71566/jarvis-voice-ai"
API = "https://api.github.com"
ALIASES = frozenset({"opus", "sonnet", "haiku", "fable", "default"})

# Boundary rule. Before: not [\w.-]; a "/" is allowed so the vendor-prefixed
# form "anthropic/claude-fable-5" (same model) is replaced. After: not [\w-]
# and not ".digit", so "claude-fable-5" never matches inside "claude-fable-5-1".
_BEFORE = r"(?<![\w.-])"
_AFTER = r"(?![\w-]|\.\d)"
_TRAIL_COMMENT = re.compile(r"\s#")


def branch_name(old: str, new: str) -> str:
    raw = f"mortimer/model-sync-{old}-to-{new}".lower()
    return re.sub(r"[^a-z0-9._/-]", "-", raw)


def _check_new(new: str) -> None:
    if ids.parse(new) is None or new.strip().lower() in ALIASES:
        raise ValueError(f"refusing alias or unrecognised model id: {new!r}")


def replace_exact(text: str, old: str, new: str) -> tuple[str, int]:
    """Replace whole-token ``old`` with ``new``; skip comment-only lines and
    the trailing ``  # comment`` part of a line. A ``#`` preceded by
    whitespace starts a comment, even inside a string (documented limit).
    Returns (new_text, count)."""
    _check_new(new)
    if not old or old == new:
        return text, 0
    pat = re.compile(_BEFORE + re.escape(old) + _AFTER)
    count = 0
    out: list[str] = []
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("#"):
            out.append(line)
            continue
        m = _TRAIL_COMMENT.search(line)
        code, tail = (line[:m.start()], line[m.start():]) if m else (line, "")
        code, n = pat.subn(lambda _m: new, code)
        count += n
        out.append(code + tail)
    return "".join(out), count


def render_body(old: str, new: str, evidence: dict, files: list[str]) -> str:
    evidence = evidence or {}
    flist = ", ".join(f"`{f}`" for f in files) or "(no files)"
    cert = evidence.get("certification") or {}
    rows = ["| Step | Result | Detail |", "| --- | --- | --- |"]
    for s in cert.get("steps") or []:
        detail = str(s.get("detail", "")).replace("|", "\\|").replace("\n", " ")
        rows.append(f"| {s.get('name')} | {'pass' if s.get('ok') else 'FAIL'} | {detail} |")
    if len(rows) == 2:
        rows.append("| (none) | - | - |")
    manual = cert.get("manual") or []
    manual_md = "\n".join(f"- `{m}`" for m in manual) or "- none"
    return "\n".join([
        f"Before: Mortimer pins `{old}` in {flist}.",
        "",
        f"After: Mortimer pins `{new}` in {flist}.",
        "",
        f"Why: {evidence.get('reason', 'newer release')}",
        "",
        "Certification:",
        "",
        *rows,
        "",
        "Manual checks still to run:",
        "",
        manual_md,
        "",
        "Opened by Mortimer's daily model check (WS-41). Nothing switches until Larry merges and redeploys.",
        "",
        "🤖 Generated by Mortimer's daily model check",
    ])


def _scrub(text: Any, token: str | None) -> str:
    out = str(text)
    if token:
        out = out.replace(token, "<redacted>")
    return out[:300]


class _ApiError(Exception):
    pass


def _result(status, branch, url=None, patch=None, error=None) -> dict[str, Any]:
    return {"status": status, "url": url, "branch": branch, "patch": patch, "error": error}


def _propose_local(old, new, files, evidence, status_dir, repo_root, branch) -> dict[str, Any]:
    chunks: list[str] = []
    for f in files:
        p = Path(repo_root) / f
        try:
            before = p.read_text(encoding="utf-8")
        except OSError:
            continue
        after, n = replace_exact(before, old, new)
        if n:
            chunks.extend(difflib.unified_diff(before.splitlines(keepends=True),
                                               after.splitlines(keepends=True),
                                               fromfile=f"a/{f}", tofile=f"b/{f}"))
    if not chunks:
        return _result("no_change", branch)
    dest = Path(status_dir) / "model-sync" / "proposals" / f"{old}-to-{new}.patch"
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(dest.parent), prefix=".patch-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write("".join(chunks))
        os.replace(tmp, dest)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    return _result("proposal_written", branch, patch=str(dest))


def propose(old: str, new: str, files: list[str], evidence: dict, *, status_dir: Path,
            token: str | None = None, repo: str | None = None, base: str = "next",
            http=None, now=None, repo_root: Path | None = None) -> dict[str, Any]:
    branch = branch_name(old, new)
    if token is None:
        token = (os.environ.get("JARVIS_GITHUB_TOKEN") or os.environ.get("GITHUB_TOKEN") or "").strip()
    token = (token or "").strip() or None
    try:
        _check_new(new)
        if not token:
            return _propose_local(old, new, files, evidence, status_dir,
                                  repo_root or REPO_ROOT, branch)
        repo = (repo or os.environ.get("JARVIS_GITHUB_REPO") or DEFAULT_REPO).strip()
        owner = repo.split("/", 1)[0]
        headers = {"Authorization": f"Bearer {token}",
                   "Accept": "application/vnd.github+json",
                   "X-GitHub-Api-Version": "2022-11-28"}
        client = http
        own = False
        if client is None:
            import httpx
            client = httpx.Client(timeout=20)
            own = True

        def call(method, path, ok=(200, 201), **kw):
            resp = client.request(method, f"{API}{path}", headers=headers, timeout=20, **kw)
            if resp.status_code not in ok:
                raise _ApiError(f"GitHub {method} {path.split('?')[0]} -> {resp.status_code}")
            return resp

        try:
            prs = call("GET", f"/repos/{repo}/pulls?state=open&head={owner}:{branch}").json()
            if prs:
                return _result("pr_exists", branch, url=prs[0].get("html_url"))
            sha = call("GET", f"/repos/{repo}/git/ref/heads/{base}").json()["object"]["sha"]
            resp = call("POST", f"/repos/{repo}/git/refs", ok=(200, 201, 422),
                        json={"ref": f"refs/heads/{branch}", "sha": sha})
            if resp.status_code == 422 and "already exists" not in str(resp.text):
                raise _ApiError("GitHub POST git/refs -> 422")
            changed: list[str] = []
            for f in files:
                got = call("GET", f"/repos/{repo}/contents/{f}?ref={branch}").json()
                before = base64.b64decode(got["content"]).decode("utf-8")
                after, n = replace_exact(before, old, new)
                if not n:
                    continue
                call("PUT", f"/repos/{repo}/contents/{f}", json={
                    "message": f"Model sync: {old} -> {new} in {f}",
                    "content": base64.b64encode(after.encode("utf-8")).decode("ascii"),
                    "sha": got["sha"], "branch": branch})
                changed.append(f)
            if not changed:
                return _result("no_change", branch)
            pr = call("POST", f"/repos/{repo}/pulls", json={
                "title": f"Model sync: {old} -> {new}", "head": branch, "base": base,
                "body": render_body(old, new, evidence, changed), "draft": False}).json()
            return _result("pr_opened", branch, url=pr.get("html_url"))
        finally:
            if own:
                client.close()
    except Exception as exc:  # noqa: BLE001
        return _result("error", branch, error=_scrub(exc, token))
